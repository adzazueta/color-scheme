/**
 * Converts linear light to an 8-bit sRGB channel value: the integer from 0 to 255 whose encoded
 * interval contains the value. This is `Math.round(255 * encoded)` in exact arithmetic, where
 * `encoded` is the inverse of the transfer function in `srgb.ts`, so a value exactly at a
 * midpoint would round up (no double lies exactly at one, so this never applies). It undoes
 * `srgbToLinear`: `linearToSrgb(srgbToLinear(i)) === i` for every integer `i` from 0 to 255.
 *
 * Exact for every double: it only compares the value with the thresholds above, in the eight fixed
 * steps of a binary search.
 *
 * @param value - Linear light, from 0 to 1. Values below 0 give 0 and values above 1 give 255, so
 *   tiny rounding excursions, such as -1e-17, land on the nearest channel value. `NaN` gives `NaN`.
 */
export function linearToSrgb(value: number): number {
  if (Number.isNaN(value)) {
    return Number.NaN;
  }
  // The channel value is the number of thresholds at or below the value. Each step adds its size
  // when the value reaches the threshold just below the larger candidate.
  let channel = 0;
  for (let step = 128; step >= 1; step /= 2) {
    if (value >= LINEAR_THRESHOLDS[channel + step - 1]!) {
      channel += step;
    }
  }
  return channel;
}
