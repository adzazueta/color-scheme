import { arch, cpus, platform, release, totalmem } from "node:os";
import { table } from "./render.js";

export interface BenchmarkRow {
  readonly label: string;
  readonly seeds: string;
  readonly mean: number;
  readonly p99: number;
  readonly max: number;
  readonly samples: number;
}

// The same JSON reporter schema read by .github/workflows/ci.yml.
interface BenchmarkJson {
  readonly testResults: readonly {
    readonly assertionResults: readonly {
      readonly title: string;
      readonly status: string;
      readonly meta?: { readonly schemesPerSample?: number };
      readonly benchmarks?: readonly {
        readonly tasks: readonly {
          readonly name: string;
          readonly latency: {
            readonly mean: number;
            readonly p99: number;
            readonly max: number;
            readonly samplesCount: number;
          };
        }[];
      }[];
    }[];
  }[];
}

/** Whole-set samples compute 11 schemes, so report their time per scheme, exactly as CI does. */
export function benchmarkRows(text: string): BenchmarkRow[] {
  const report = JSON.parse(text) as BenchmarkJson;
  const rows: BenchmarkRow[] = [];
  for (const file of report.testResults) {
    for (const test of file.assertionResults) {
      if (test.status !== "passed") throw new Error(`Benchmark failed: ${test.title}.`);
      const schemes = test.meta?.schemesPerSample ?? 1;
      if (!Number.isInteger(schemes) || schemes < 1) throw new Error("Invalid schemes per sample.");
      for (const benchmark of test.benchmarks ?? []) {
        for (const task of benchmark.tasks) {
          const { mean, p99, max, samplesCount } = task.latency;
          if (
            ![mean, p99, max, samplesCount].every((value) => Number.isFinite(value) && value > 0)
          ) {
            throw new Error("Invalid benchmark measurement.");
          }
          rows.push({
            label: test.title,
            seeds: task.name,
            mean: mean / schemes,
            p99: p99 / schemes,
            max: max / schemes,
            samples: samplesCount,
          });
        }
      }
    }
  }
  if (rows.length === 0) throw new Error("The benchmark report has no results.");
  return rows;
}

export function renderBenchmarks(
  rows: readonly BenchmarkRow[],
  algorithmVersion: string,
  packageVersion: string,
  commit: string,
  generatedAt: string,
): string {
  const cpu = cpus();
  return (
    [
      "# Benchmark report",
      "Generated by `vp run eval`, running the existing `bench/create.bench.ts` benchmarks on the built package. This is the local measurement for the 5 ms target (specification 10.2).",
      table(
        ["Field", "Value"],
        [
          ["Algorithm version", algorithmVersion],
          ["Package version", packageVersion],
          ["Commit", commit],
          ["Date", generatedAt],
          ["CPU", cpu[0]?.model ?? "Unknown CPU"],
          ["Cores", String(cpu.length)],
          ["Memory", `${(totalmem() / 1024 ** 3).toFixed(1)} GiB`],
          ["Operating system", `${platform()} ${release()} (${arch()})`],
          ["Node", process.version],
          ["Options", "time 500 ms, warmup time 100 ms per case"],
        ],
      ),
      "## Results",
      "Times are milliseconds per complete light-and-dark scheme, measured on `dist/index.js`. Decoding and color extraction are outside the timed work. Whole-set samples compute every benchmark seed; their times are divided by 11. Timing measurements vary with machine load.",
      table(
        ["Case", "Seeds", "Mean (ms)", "p99 (ms)", "Max (ms)", "Samples"],
        rows.map((row) => [
          row.label,
          row.seeds,
          row.mean.toFixed(6),
          row.p99.toFixed(6),
          row.max.toFixed(6),
          String(row.samples),
        ]),
      ),
      `Cases with mean below 5 ms: ${rows.filter((row) => row.mean < 5).length} / ${rows.length}.`,
    ].join("\n\n") + "\n"
  );
}
