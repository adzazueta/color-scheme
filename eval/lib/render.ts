import {
  ACCENT_SEEDS,
  MODES,
  SEEDS,
  SOURCES,
  type CoverResult,
  type Report,
  type Summary,
} from "./report.js";

/** Pad generated Markdown tables like the reference evaluation, without a formatter pass. */
export function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const cells = [headers, ...rows].map((row) => row.map((cell) => cell.replaceAll("|", "\\|")));
  const heading = cells[0]!;
  const body = cells.slice(1);
  const widths = heading.map((header, index) =>
    Math.max(3, header.length, ...body.map((row) => row[index]?.length ?? 0)),
  );
  const line = (row: readonly string[]): string =>
    `| ${row.map((cell, i) => cell.padEnd(widths[i] ?? 3)).join(" | ")} |`;
  return [line(heading), line(widths.map((width) => "-".repeat(width))), ...body.map(line)].join(
    "\n",
  );
}

export function summaryRows(summary: Summary): string[][] {
  return SEEDS.flatMap((seed) =>
    MODES.map((mode) => {
      const item = summary.fidelity[seed][mode];
      return [
        seed,
        mode,
        `${item.exact} / ${item.given}`,
        item.averageAbsoluteLightnessShift?.toFixed(6) ?? "n/a",
      ];
    }),
  );
}

export function placementRows(summary: Summary): string[][] {
  return ACCENT_SEEDS.flatMap((seed) =>
    MODES.flatMap((mode) =>
      SOURCES.map((source) => {
        const item = summary.placement[seed][mode][source];
        return [
          seed,
          mode,
          source,
          String(item.total),
          String(item.exactX),
          String(item.exactContainer),
          String(item.moved),
        ];
      }),
    ),
  );
}

const PLACEMENT_HEADERS = [
  "Seed",
  "Mode",
  "Source",
  "Total",
  "Exact X",
  "Exact container",
  "Moved",
];
const PLACEMENT_LABELS = { exactX: "exact X", exactContainer: "exact container", moved: "moved" };

export function renderSummary(summary: Summary): string {
  return [
    `Covers: ${summary.covers}. Neutral themes: ${summary.neutralThemes}. Verification failures: ${summary.verificationFailures}.`,
    "Fidelity measures given seeds only, using ModeReport.adjustments. Derived seeds are excluded. The denominator is the number of covers where that seed was given; an empty mean is n/a. Shifts are absolute Oklab lightness differences (0 to 1); they do not measure chroma changes.",
    table(["Seed", "Mode", "Exact / given", "Mean |lightnessShift|"], summaryRows(summary)),
    "Placement compares each accent seed's hex with X first, then its container: exact X, exact container, or moved. Counts include given and derived seeds separately, per mode; each seed appears exactly once. Fidelity counts an exact seed in either role and therefore can stay unchanged when placement changes.",
    table(PLACEMENT_HEADERS, placementRows(summary)),
    table(
      ["Seed", "Given", "Derived"],
      SEEDS.map((seed) => [
        seed,
        String(summary.sources[seed].given),
        String(summary.sources[seed].derived),
      ]),
    ),
  ].join("\n\n");
}

export function renderJson(report: Report): string {
  return `${JSON.stringify(report, null, 2)}\n`;
}

export function renderMarkdown(report: Report): string {
  const h = report.header;
  const blocks = [
    `# Evaluation report: ${report.set === "dev" ? "development" : "test"} set`,
    "Generated by `vp run eval`. Only cover ids, colors, and results are published. The local HTML contains the visual review.",
    table(
      ["Field", "Value"],
      [
        ["Algorithm version", h.algorithmVersion],
        ["Variant", h.variant],
        ["Package version", h.packageVersion],
        ["Commit", h.commit],
        ["Date", h.generatedAt],
        ["Extractor", `${h.extractor.packageVersion}, algorithm ${h.extractor.algorithmVersion}`],
        ["Extraction", "perceptual, count 5, default decoder limits"],
        ["Decoder", `sharp ${h.decoder.sharp}, libvips ${h.decoder.libvips}`],
        ["Annotations SHA-256", h.annotationsSha256],
      ],
    ),
    "## Fidelity summary",
    renderSummary(report.summary),
    "## Covers",
  ];
  for (const cover of report.covers) {
    blocks.push(`### ${cover.id}`);
    blocks.push(
      `Neutral theme: ${cover.neutralTheme ? "yes" : "no"}. Verification failures: ${cover.verificationFailures.length}.`,
    );
    blocks.push(
      table(
        ["Extracted color", "Coverage"],
        cover.colors.map((c) => [c.hex, c.coverage.toFixed(6)]),
      ),
    );
    blocks.push(
      table(
        ["Seed", "Hex", "Source"],
        SEEDS.map((seed) => [seed, cover.scheme.seeds[seed].hex, cover.scheme.seeds[seed].source]),
      ),
    );
    blocks.push(
      table(
        ["Role", "Light", "Dark"],
        Object.keys(cover.scheme.light).map((role) => {
          const key = role as keyof typeof cover.scheme.light;
          return [role, cover.scheme.light[key], cover.scheme.dark[key]];
        }),
      ),
    );
    blocks.push(
      table(
        ["Mode", "Seed", "Role", "Exact", "lightnessShift"],
        MODES.flatMap((mode) =>
          cover.scheme.report[mode].adjustments.map((a) => [
            mode,
            a.seed,
            a.role,
            String(a.exact),
            a.lightnessShift.toFixed(6),
          ]),
        ),
      ),
    );
  }
  return `${blocks.join("\n\n")}\n`;
}

export function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function swatch(hex: string, label: string): string {
  return `<div class="swatch"><span style="background:${escapeHtml(hex)}"></span><code>${escapeHtml(label)}<br>${escapeHtml(hex)}</code></div>`;
}

function coverHtml(cover: CoverResult, image: string): string {
  const scheme = cover.scheme;
  return `<article id="${cover.id}"><h2>${cover.id}${cover.neutralTheme ? " · neutral theme" : ""}</h2>
<div class="overview"><img src="${escapeHtml(image)}" alt="Cover ${cover.id}" loading="lazy"><div><h3>Extracted colors</h3><div class="swatches">${cover.colors.map((c) => swatch(c.hex, `${(c.coverage * 100).toFixed(2)}%`)).join("")}</div><h3>Seeds</h3><div class="swatches">${SEEDS.map((seed) => swatch(scheme.seeds[seed].hex, `${seed} (${scheme.seeds[seed].source})`)).join("")}</div></div></div>
<div class="modes">${MODES.map((mode) => {
    const r = scheme[mode];
    return `<section><h3>${mode}</h3><p class="placement">${ACCENT_SEEDS.map((seed) => `${seed} (${scheme.seeds[seed].source}): <strong>${PLACEMENT_LABELS[cover.placement[seed][mode]]}</strong>`).join(" · ")}</p><div class="sample" style="background:${r.surface};color:${r.onSurface};border-color:${r.outline}"><h4>Your reading shelf</h4><p style="color:${r.onSurfaceVariant}">A theme inspired by this cover.</p><button type="button" style="background:${r.primary};color:${r.onPrimary};border-color:${r.primary}">Continue reading</button> <button type="button" style="background:${r.secondary};color:${r.onSecondary};border-color:${r.secondary}">Save</button><div class="container" style="background:${r.surfaceContainer};border-color:${r.outline}">Chapter one <span style="color:${r.onSurfaceVariant}">Ready to read</span></div><p class="status" style="background:${r.successContainer};color:${r.onSuccessContainer}">Your place has been saved.</p></div><details open><summary>34 roles</summary><div class="swatches roles">${Object.entries(
      r,
    )
      .map(([role, hex]) => swatch(hex, role))
      .join(
        "",
      )}</div></details><h4>Given-seed adjustments</h4><table><thead><tr><th>Seed</th><th>Role</th><th>Exact</th><th>Lightness shift</th></tr></thead><tbody>${scheme.report[mode].adjustments.map((a) => `<tr><td>${a.seed}</td><td>${a.role}</td><td>${a.exact}</td><td>${a.lightnessShift.toFixed(6)}</td></tr>`).join("")}</tbody></table></section>`;
  }).join("")}</div></article>`;
}

